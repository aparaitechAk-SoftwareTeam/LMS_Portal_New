const { Task } = require('../models/ProjectTask');

const phases = [
  ['Phase 1 · Understand & Plan', ['Read the project brief and identify the final outcome', 'Set up the local workspace and required tools', 'Research the target users, references and key requirements', 'Write the feature list and define acceptance criteria', 'Submit the project plan and get ready to build']],
  ['Phase 2 · Design & Foundation', ['Create the architecture or project structure', 'Prepare data models, screens or core components', 'Set up version control and the development branch', 'Build the first working foundation', 'Test the foundation and record the first milestone']],
  ['Phase 3 · Build & Integrate', ['Implement the first main feature', 'Implement the second main feature', 'Connect interfaces, APIs or project modules', 'Handle validation, edge cases and error states', 'Run an end-to-end integration test']],
  ['Phase 4 · Quality & Delivery', ['Test all important user flows', 'Fix issues and improve code quality', 'Prepare project documentation and README', 'Deploy or package the final project', 'Submit final links, evidence and project walkthrough']],
];

exports.generateProjectWorkflow = async (project, adminId) => {
  const existing = await Task.countDocuments({ project: project._id, isAutoGenerated: true });
  if (existing) return { created: 0, total: existing };
  const start = project.startDate ? new Date(project.startDate) : new Date();
  const end = project.endDate ? new Date(project.endDate) : new Date(start.getTime() + 30 * 24 * 60 * 60 * 1000);
  const span = Math.max(1, end.getTime() - start.getTime());
  const rows = phases.flatMap(([phase, steps], phaseIndex) => steps.map((step, stepIndex) => {
    const sequence = phaseIndex * 5 + stepIndex + 1;
    const dueDate = new Date(start.getTime() + span * (sequence / 20));
    return {
      title: `${project.title} — ${step}`,
      description: `Part ${phaseIndex + 1} of 4. Complete this step for the ${project.title} live project before moving to the next task.`,
      instructions: `Read the task carefully, complete the required work in your project, then mark it complete. Evidence such as a GitHub link, screenshot, document or deployed link can be added in the task submission.`,
      type: 'project', priority: phaseIndex >= 2 ? 'high' : 'medium', assignedTo: project.assignedTo,
      project: project._id, dueDate, createdBy: adminId, phase, sequence, isAutoGenerated: true,
      tags: ['live-project', `phase-${phaseIndex + 1}`],
    };
  }));
  await Task.insertMany(rows);
  project.autoWorkflowGenerated = true;
  if (!project.startDate) project.startDate = start;
  if (!project.endDate) project.endDate = end;
  if (!project.milestones?.length) project.milestones = phases.map(([title], index) => ({ title, description: `Complete all five tasks in ${title}.`, dueDate: new Date(start.getTime() + span * ((index + 1) / 4)) }));
  await project.save();
  return { created: rows.length, total: rows.length };
};
